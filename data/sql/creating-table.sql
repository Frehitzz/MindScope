  stress_level INTEGER,
  anxiety_level INTEGER,
  addiction_level INTEGER,
  depression_label INTEGER,
  age_was_missing INTEGER,
  gender_was_missing INTEGER,
  daily_social_media_hours_was_missing INTEGER,
  platform_usage_was_missing INTEGER,
  sleep_hours_was_missing INTEGER,
